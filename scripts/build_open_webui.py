#!/usr/bin/env python3
"""Build grimoire's Open WebUI filter and tool, each one file with its modules inlined; or check they are current.

    python scripts/build_open_webui.py            # writes open-webui/grimoire_filter.py and grimoire_tool.py
    python scripts/build_open_webui.py --check    # exits 1 if either differs from what would be written

Open WebUI keeps a function or a tool as one file in its database, so each carries the core, the ledger reader
and the port's own code, inlined verbatim in that order. The lines importing one inlined module from another
are dropped, whether flat, relative or from the `grimoire` package, and each module is bound under its name after it, so `lorebookcore.select` still reads as written.
A top-level name defined in two modules stops the build, since the later would silently replace the earlier.
"""

import argparse
import ast
import pathlib
import re
import subprocess
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
SOURCE = REPO / "open-webui" / "src"
OUT = REPO / "open-webui"

# Name -> source, in the order they are inlined; a later module may import an earlier one.
MODULES = {
    "lorebookcore": REPO / "grimoire" / "lorebookcore.py",
    "ledger": REPO / "grimoire" / "ledger.py",
    "lorebook_settings": SOURCE / "lorebook_settings.py",
}
TARGETS = {
    "grimoire_filter.py": ("filter", SOURCE / "filter.py",
                           "Gives the model the definitions of your own terms when a term comes up in the conversation."),
    "grimoire_tool.py": ("tool", SOURCE / "tool.py",
                         "Lets the model look up a term in your lorebook: your own definitions of your own terms."),
}
REQUIRED_OPEN_WEBUI = "0.11.2"  # the `request` hook

# The same import in two modules binds the same object, so it is no clash; neither is a module's `__all__`.
_HARMLESS = {"__all__"}
_IMPORT_OF_INLINED = re.compile(r"^(import (?P<plain>\w+)|from (?:\.|grimoire) import (?P<names>\w+(?:, \w+)*)"
                                r"|from (?P<from>\w+) import .*)\n", re.MULTILINE)


def _top_level_names(source: str) -> tuple[set[str], set[str]]:
    """`(defined, imported)`: the names a module binds at top level by definition, and by import."""
    defined, imported = set(), set()
    for node in ast.parse(source).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            defined.add(node.name)
        elif isinstance(node, ast.Assign):
            defined |= {target.id for target in node.targets if isinstance(target, ast.Name)}
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            defined.add(node.target.id)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            imported |= {(alias.asname or alias.name).split(".")[0] for alias in node.names}
    return defined - _HARMLESS, imported

def _without_inlined_imports(source: str, inlined: set[str]) -> str:
    def keep(match: re.Match) -> str:
        if match.group("names"):
            names = set(match.group("names").split(", "))
            if not names <= inlined:
                sys.exit(f"build_open_webui: {match.group(0).strip()!r} imports {sorted(names - inlined)}, not inlined before it")
            return ""
        return "" if (match.group("plain") or match.group("from")) in inlined else match.group(0)
    return _IMPORT_OF_INLINED.sub(keep, source)

def _raven_commit() -> str:
    return (REPO / "grimoire" / "RAVEN_COMMIT").read_text(encoding="utf-8").strip()[:12]

def _grimoire_commit() -> str:
    result = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--short=12", "HEAD"], capture_output=True, text=True)
    return result.stdout.strip() or "unknown"

def build(kind: str, port: pathlib.Path, description: str) -> str:
    """The text of one generated file."""
    parts = [*MODULES.items(), (kind, port)]
    owners: dict[str, str] = {}
    imports: set[str] = set()
    for name, path in parts:
        defined, imported = _top_level_names(path.read_text(encoding="utf-8"))
        clashes = (defined & set(owners)) | (defined & imports)
        if clashes:
            sys.exit(f"build_open_webui: {name} redefines {sorted(clashes)}, already bound by an earlier part")
        owners.update(dict.fromkeys(defined, name))
        imports |= imported

    # Open WebUI reads the frontmatter from the file's opening docstring.
    out = [f'"""\ntitle: grimoire lorebook ({kind})\nauthor: Juha Jeronen\n'
           f"author_url: https://github.com/Technologicat\nfunding_url: https://github.com/Technologicat/grimoire\n"
           f"version: 0.1.0\nlicense: BSD-2-Clause\nrequired_open_webui_version: {REQUIRED_OPEN_WEBUI}\n"
           f'description: {description}\n"""\n',
           f"# Generated by grimoire's scripts/build_open_webui.py from grimoire {_grimoire_commit()}, with the core\n"
           f"# from Raven {_raven_commit()}. Do not edit: edit the sources in the grimoire repository and build again.\n"
           f"# https://github.com/Technologicat/grimoire\n\n"
           f"import types as _grimoire_types\n"]
    inlined: set[str] = set()
    for name, path in parts:
        source = _without_inlined_imports(path.read_text(encoding="utf-8"), inlined)
        # As a POSIX path, so that the file comes out the same on every OS.
        out.append(f"\n\n# {'=' * 100}\n# {path.relative_to(REPO).as_posix()}\n# {'=' * 100}\n\n{source}")
        if name in MODULES:
            out.append(f"\n{name} = _grimoire_types.SimpleNamespace(**{{_name: _value for _name, _value in "
                       f"globals().items() if not _name.startswith('__')}})\n")
        inlined.add(name)
    return "".join(out)

def _without_provenance(text: str) -> str:
    """The text with its commit line blanked, so a commit that changes no source leaves the file current."""
    return re.sub(r"from grimoire \w+,", "from grimoire -,", text)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is not current")
    args = parser.parse_args()
    current = True
    for filename, (kind, port, description) in TARGETS.items():
        text = build(kind, port, description)
        path = OUT / filename
        if args.check:
            same = path.exists() and _without_provenance(path.read_text(encoding="utf-8")) == _without_provenance(text)
            print(f"{'      ok' if same else ' STALE  '}  {path.relative_to(REPO)}")
            current &= same
        else:
            path.write_text(text, encoding="utf-8")
            print(f"   built  {path.relative_to(REPO)}")
    if args.check and not current:
        sys.exit("Run python scripts/build_open_webui.py, and commit the result.")


if __name__ == "__main__":
    main()
