#!/usr/bin/env python3
"""Write the cases the TypeScript `difflib` is checked against, computed by Python's own `difflib`.

    python scripts/make_difflib_cases.py            # writes ts/core/test/difflib_cases.json
    python scripts/make_difflib_cases.py --check    # exits 1 if the file differs from what would be written

The cases favour what a translation gets wrong: ties broken by the strings, letters past the Basic Multilingual
Plane, and a second sequence long enough for the `autojunk` heuristic.
"""

import argparse
import difflib
import json
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "ts" / "core" / "test" / "difflib_cases.json"

PAIRS = [
    ("", ""), ("abc", ""), ("", "abc"), ("abc", "abc"), ("abcd", "bcde"), ("ab", "acab"),
    ("hydra tax", "hydra taxes"), ("introspection", "miroconnection"), ("aria-worthy", "aria-worthy design"),
    ("kaupunki", "kaupungissa"), ("päivä", "paiva"), ("naïve", "naive"),
    ("\U0001d4b6bc", "abc"), ("\U0001f600 smile", "\U0001f600 smiles"), ("\ue000x", "\U00010000x"),
    ("ab" * 150, "ba" * 150), ("a" * 120 + "b" * 100, "a" * 100 + "b" * 120),
    ("the quick brown fox " * 12, "the quick brown dog " * 12),
]

# a, b, the junk elements (or None), autojunk
JUNK = [
    ("private Thread currentThread;", "private volatile Thread currentThread;", " ", True),  # Python's docs' example
    ("a b c d", "a  b  c  d", " ", True),
    ("abxcd", "abcd", "x", True),
    ("ab" * 150, "ba" * 150, None, False),
    ("a" * 120 + "b" * 100, "a" * 100 + "b" * 120, None, False),
    ("x" + "a b " * 60, "a b " * 60 + "x", " ", False),
]

CLOSE = [
    # word, possibilities, n, cutoff
    ("appel", ["ape", "apple", "peach", "puppy"], 3, 0.6),
    ("ab", ["ba", "ab", "aa", "bb"], 4, 0.0),          # equal scores: reverse string order
    ("abc", ["abd", "abe", "abf", "xbc"], 2, 0.6),
    ("hydra tax", ["hydra tax", "hydra taxes", "attention rent", "hydratax"], 5, 0.8),
    ("\U0001f600a", ["\ue000a", "\U0001f601a", "\U00010000a"], 3, 0.0),   # code point order past the BMP
    ("introspection", ["miroconnection", "introspective", "inspection"], 5, 0.8),
]


def build() -> str:
    def ratios(a, b, junk=None, autojunk=True):
        isjunk = (lambda element: element in junk) if junk is not None else None
        matcher = difflib.SequenceMatcher(isjunk, a, b, autojunk=autojunk)
        return {"a": a, "b": b, "junk": junk, "autojunk": autojunk,
                "ratio": matcher.ratio(), "quick_ratio": matcher.quick_ratio(),
                "real_quick_ratio": matcher.real_quick_ratio(),
                "blocks": [list(block) for block in matcher.get_matching_blocks()]}
    cases = {"about": "Generated by scripts/make_difflib_cases.py with Python's difflib; do not edit.",
             "python": sys.version.split()[0],
             "pairs": [ratios(a, b) for a, b in PAIRS] + [ratios(*case) for case in JUNK],
             "close": [{"word": word, "possibilities": possibilities, "n": n, "cutoff": cutoff,
                        "expect": difflib.get_close_matches(word, possibilities, n=n, cutoff=cutoff)}
                       for word, possibilities, n, cutoff in CLOSE]}
    return json.dumps(cases, indent=1) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file is not current")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.exists() and json.loads(OUT.read_text(encoding="utf-8")) | {"python": None} == \
            json.loads(text) | {"python": None}
        print(f"{'ok' if current else 'STALE'}  {OUT.name}")
        sys.exit(0 if current else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
